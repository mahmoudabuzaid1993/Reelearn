export function toListItem(reel: Reel, awaiting: string | null): ReelListItem {
  const topic = topics.find((t) => t.id === reel.topic_id);
  return {
    id: reel.id,
    topic: { id: reel.topic_id, name: topic?.name ?? "" },
    kind: reel.kind,
    status: reel.status,
    title: reel.title,
    language: reel.language,
    languages: [reel.language, ...(reel.variants ?? []).map((v) => v.language).filter((l): l is string => Boolean(l))],
    duration_ms: reel.duration_ms ?? null,
    thumbnail_url: reel.thumbnail_url ?? null,
    version: reel.version,
    recall_pct: reel.recall_pct ?? null,
    plays: reel.status === "published" ? 20 + reel.title.length : 0,
    awaiting,
    updated_at: reel.updated_at ?? reel.created_at,
    quality: reel.quality ?? null,
  };
}
